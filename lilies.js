/* The one thing that changes with the screen: how much the whole box is scaled. */
function fitBouquet() {
  const scale = Math.min(
    (innerWidth - MARGIN_X) / (designWidth * UNIT_PX),
    (innerHeight - MARGIN_Y) / (designHeight * UNIT_PX)
  );
  stage.style.setProperty("--s", scale.toFixed(4));
}

