/* Collects the visible extent of everything in the bouquet: x from the centre, y up. */
function newBox() {
  return {
    minX: Infinity,
    maxX: -Infinity,
    maxY: 0,
    add(x, y) {
      this.minX = Math.min(this.minX, x);
      this.maxX = Math.max(this.maxX, x);
      this.maxY = Math.max(this.maxY, y);
    },
    /* Adds a point given in SVG units, where the bouquet's base is at (50, 100). */
    addSvg(x, y, pad = 0) {
      this.add(x - 50 - pad, 100 - y + pad);
      this.add(x - 50 + pad, 100 - y - pad);
    },
  };
}

/* Adds the visible petals and stamens of a head, as it is rotated and mirrored. */
function addHeadToBox(box, lily) {
  const outline = HEAD_OUTLINES[lily.head - 1];
  const turn = (lily.turn * Math.PI) / 180;
  const flip = lily.flip ? -1 : 1;
  outline.forEach((reach, i) => {
    for (const offset of [0, 0.5, 1]) {
      const angle = ((i + offset) * 2 * Math.PI) / outline.length;
      const px = Math.cos(angle) * reach * lily.size * flip;
      const py = Math.sin(angle) * reach * lily.size;
      const x = px * Math.cos(turn) - py * Math.sin(turn);
      const y = px * Math.sin(turn) + py * Math.cos(turn);
      box.add(lily.x + x, lily.y - y);
    }
  });
}

/* A broad, pointed leaf from (ax, ay) to (tx, ty), drooping a little at the tip. */
function leafMarkup(ax, ay, tx, ty, widthBase, delay, tone, box) {
  const dx = tx - ax;
  const dy = ty - ay;
  const length = Math.hypot(dx, dy);
  const ux = dx / length;
  const uy = dy / length;
  const nx = -uy;
  const ny = ux;
  const tipY = ty + length * 0.04;
  const half = widthBase * 0.12 * 2;
  const bend = -widthBase * 0.06 * Math.sign(dx || 1);
  const ctrl = (along, across) => [
    ax + ux * length * along + nx * across,
    ay + uy * length * along + ny * across,
  ];
  const c1 = ctrl(0.4, half + bend);
  const c2 = ctrl(0.4, -half + bend);
  const pt = (p) => `${n(p[0])} ${n(p[1])}`;
  const shape = `M${pt([ax, ay])}Q${pt(c1)} ${pt([tx, tipY])}Q${pt(c2)} ${pt([ax, ay])}Z`;
  const rib = `M${pt([ax, ay])}Q${pt(ctrl(0.4, bend))} ${pt([tx, tipY])}`;

  for (let t = 0; t <= 1.001; t += 0.1) {
    const quad = (p0, c, p2) =>
      [0, 1].map((i) => (1 - t) ** 2 * p0[i] + 2 * (1 - t) * t * c[i] + t * t * p2[i]);
    for (const [x, y] of [quad([ax, ay], c1, [tx, tipY]), quad([tx, tipY], c2, [ax, ay])]) {
      box.addSvg(x, y);
    }
  }
  return (
    `<g class="leaf leaf--${tone}" style="transform-origin:${n(ax)}px ${n(ay)}px; --leaf-delay:${n(delay)}s">` +
    `<path class="leaf__blade" d="${shape}"/><path class="leaf__rib" d="${rib}"/></g>`
  );
}

function fanMarkup(box) {
  const paths = LEAVES.map(([reach, height, tone], i) => {
    const widthBase = Math.hypot(reach, height);
    return leafMarkup(50, 100, 50 + reach, 100 - height, widthBase, 0.1 + i * 0.12, tone, box);
  }).join("");
  return `<div class="bouquet__fan"><svg class="plant" viewBox="0 0 100 100" preserveAspectRatio="none" aria-hidden="true">${paths}</svg></div>`;
}

/* The stem is one gentle curve from the shared base to the head: it leaves the base
   nearly upright, then bends outward toward the head. */
function stemCurve(bx, by, hx, hy) {
  const dx = hx - bx;
  const dy = by - hy;
  return [
    [bx, by],
    [bx + dx * 0.05, by - dy * 0.42],
    [hx - dx * 0.22, hy + dy * 0.3],
    [hx, hy],
  ];
}

function pointOn([p0, p1, p2, p3], t) {
  const u = 1 - t;
  const at = (i) =>
    u * u * u * p0[i] + 3 * u * u * t * p1[i] + 3 * u * t * t * p2[i] + t * t * t * p3[i];
  return [at(0), at(1)];
}

function lilyMarkup(lily, index, box) {
  const base = lily.x * 0.07;
  const bx = 50 + base;
  const by = 100;
  const hx = 50 + lily.x;
  const hy = 100 - lily.y;
  const curve = stemCurve(bx, by, hx, hy);
  const d = `M${n(bx)} ${n(by)}C${curve.slice(1).map(([x, y]) => `${n(x)} ${n(y)}`).join(" ")}`;

  for (let t = 0; t <= 1.001; t += 0.05) {
    const [x, y] = pointOn(curve, t);
    box.addSvg(x, y, STEM_WIDTH / 2);
  }
  addHeadToBox(box, lily);

  let peek = "";
  if (lily.peek) {
    const [t, side, length, angle] = lily.peek;
    const [px, py] = pointOn(curve, t);
    const rad = (angle * Math.PI) / 180;
    peek = leafMarkup(
      px, py, px + Math.sin(rad) * side * length, py - Math.cos(rad) * length,
      length, lily.delay + 0.9, "a", box
    );
  }

  return `
    <div class="lily lily--${lily.row}" style="
      --base:${n(base)}; --head-x:${n(lily.x - base)}; --head-y:${lily.y};
      --size:${lily.size}; --turn:${lily.turn}deg; --flip:${lily.flip ? -1 : 1};
      --delay:${n(lily.delay)}s; --bloom-delay:${n(lily.delay + 1.8)}s;
      --sway:${n(3.2 + ((index * 3) % 9) * 0.3)}s; --sway-delay:${n(-index * 1.1)}s;">
      <svg class="plant" viewBox="0 0 100 100" preserveAspectRatio="none" aria-hidden="true">
        <path class="lily__stem" pathLength="1" d="${d}"/>
        ${peek}
      </svg>
      <div class="lily__bloom">
        <img class="lily__head" src="assets/lilies/head-${String(lily.head).padStart(2, "0")}.png" alt="">
      </div>
    </div>`;
}

